function bonusManager(host){
 const sec=node('section','tv254-panel tv254-bonus-choices');
 sec.append(node('div','tv254-eyebrow','DM GRANTED CHOICES'),
   node('h2','','Grant an extra proficiency choice'),
   node('p','tv254-muted','Grant one or more player-selected languages or tools; their sheet will prompt them to choose, like a level-up choice. This does not grant an unchosen or invented proficiency.'));
 const members=charsForCampaign().filter(c=>c.owner==='Party member'||c.owner==='You');
 if(!members.length){sec.append(node('p','tv254-muted','No real player characters in this campaign yet.'));host.append(sec);return}
 const form=node('form','tv254-form-row');
 const label=(s,el)=>{const x=node('label','tv254-label');x.append(node('span','',s),el);return x};
 const char=select(members.map(c=>[c.id,c.name]));
 const kind=select([['tool','Tool proficiency'],['language','Language proficiency']]);
 const pool=select([['any','Any approved option'],['artisan',"Artisan's tools"],['instrument','Musical instrument'],['game','Gaming set'],['artisan-instrument','Artisan tools or instruments']]);
 kind.addEventListener('change',()=>{pool.disabled=kind.value==='language';if(pool.disabled)pool.value='any'});
 const count=field('Number of picks',1,{type:'number',min:1,max:5});
 const note=field('Reason','DM bonus proficiency',{maxLength:240});
 form.append(label('Recipient character',char),label('Kind',kind),label('Tool category',pool),count.wrap,note.wrap);
 const send=node('button','btn primary small','Grant choice');send.type='submit';form.append(send);
 form.addEventListener('submit',async e=>{
  e.preventDefault();
  await act(api().rpc('terravale_dm_grant_proficiency_choice',{
   target_character:char.value,proficiency_kind:kind.value,
   choice_pool:kind.value==='language'?'any':pool.value,
   number_of_choices:Number(count.el.value),purpose:note.el.value
  }),'An extra '+kind.value+' choice is waiting on the player’s character sheet.');
 });
 sec.append(form);
 const pending=node('div','tv254-pending-languages');
 pending.append(node('div','tv254-form-heading','Restricted ancestry language approvals'));
 pending.append(node('p','tv254-small','Checking player language requests…'));
 sec.append(pending);
 host.append(sec);
 // The pending list comes from the actual character record, never an invented
 // choice. Only the campaign DM may confirm a restricted language.
 const ids=members.map(m=>m.id);
 api().from('terravale_character_proficiencies')
  .select('character_id,pending_languages').in('character_id',ids)
  .then(({data,error})=>{
   if(!pending.isConnected)return;
   pending.replaceChildren(node('div','tv254-form-heading','Restricted ancestry language approvals'));
   if(error){pending.append(node('p','tv254-small','Unable to retrieve pending languages: '+error.message));return}
   let count=0;
   for(const record of data||[]){
    const character=members.find(x=>x.id===record.character_id);
    for(const entry of record.pending_languages||[]){
     const language=tools().languages.find(x=>x.id===entry.id);
     if(!character||!language)continue;
     count++;
     const row=node('div','tv254-stock-row');
     row.append(node('span','',character.name+' · '+language.name),
       button('Approve language',async()=>{
        await act(api().rpc('terravale_dm_approve_language',{
         target_character:character.id,language_id:language.id
        }),'Approved '+language.name+' for '+character.name+'.');
       },'btn primary small'));
     pending.append(row);
    }
   }
   if(!count)pending.append(node('p','tv254-small','No restricted language requests are waiting.'));
  });
}
