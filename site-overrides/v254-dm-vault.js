 if(opts.max!==undefined)el.max=opts.max;
 if(opts.step!==undefined)el.step=opts.step;
 if(opts.maxLength)el.maxLength=opts.maxLength;
 if(opts.multiline)el.rows=opts.rows||4;
 wrap.append(el);
