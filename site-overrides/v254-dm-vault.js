async function fetchAllVault(){
 const campaign=currentCampaign();
 if(!campaign)return;
 const items=[];
 for(let start=0;start<2000;start+=500){
  const {data,error}=await api().from('terravale_dm_vault_items').select('*')
   .eq('campaign_id',campaign.id).order('created_at',{ascending:true}).range(start,start+499);
  if(error)throw error;
  items.push(...(data||[]));
  if(!data||data.length<500)break;
 }
 panelState.vault=items;panelState.loadedCampaign=campaign.id;
}
async function refreshCurrent(){
 try{
  // Fetch first: syncCharacters re-renders the native page, and the
  // remounted vault should already have its current stock before it opens.
  await fetchAllVault();
  await bridge()?.syncCharacters?.();
  renderVaultBody();
 }catch(e){notify('Vault refresh failed: '+(e.message||String(e)))}
}
function busy(b,description){
 panelState.busy=b;
 const status=document.querySelector('#tv254-vault-status');
 if(status)status.textContent=description||'';
}
async function act(promise,message){
 if(panelState.busy)return false;
 busy(true,'Saving securely to your campaign…');
 try{
  const {data,error}=await promise;
  if(error)throw error;
  notify(message);
  busy(false,'Saved.');
  await refreshCurrent();
  return data||true;
 }catch(error){
  busy(false,'Could not save: '+(error?.message||String(error)));
  return false;
 }
}
