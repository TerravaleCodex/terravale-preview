"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {spawnSync}=require("node:child_process");
const sql=fs.readFileSync("site-overrides/sql/neon_staging_sheet_read.sql","utf8");
const html=fs.readFileSync("site-overrides/neon-staging-auth.html","utf8");
const js=fs.readFileSync("site-overrides/neon-readonly-bridge.mjs","utf8");
assert.match(sql,/CREATE OR REPLACE FUNCTION public\.terravale_neon_staging_sheet_read\(p_character_id uuid\)/);
assert.match(sql,/LANGUAGE sql\s+STABLE/);
assert.doesNotMatch(sql,/\bSECURITY DEFINER\b/i,"Sheet is SECURITY INVOKER");
assert.match(sql,/c\.id=p_character_id/);
assert.match(sql,/auth\.uid\(\) IS NOT NULL/);
assert.match(sql,/c\.owner_id=auth\.uid\(\) OR authz\.is_dm\(c\.campaign_id\)/);
assert.match(sql,/FROM public\.characters c/);
assert.match(sql,/FROM public\.character_state s|JOIN public\.character_state s/);
assert.match(sql,/FROM public\.terravale_character_wallet w/);
assert.match(sql,/FROM public\.character_item_properties/);
assert.match(sql,/LIMIT 200/);
assert.match(sql,/REVOKE ALL ON FUNCTION public\.terravale_neon_staging_sheet_read\(uuid\) FROM PUBLIC/);
assert.match(sql,/GRANT EXECUTE ON FUNCTION public\.terravale_neon_staging_sheet_read\(uuid\) TO authenticated/);
assert.doesNotMatch(sql,/\b(?:INSERT INTO|UPDATE public\.|DELETE FROM|TRUNCATE TABLE|GRANT ALL)\b/i,"No writes or broad table grants");
assert.match(js,/terravale_neon_staging_sheet_read/);
assert.match(js,/Object\.hasOwn\(args,"p_character_id"\)/);
assert.match(js,/Read-only sheet requires one valid character UUID/);
assert.match(html,/Inspect saved sheet \(read-only\)/);
assert.match(html,/readBridge\.rpc\("terravale_neon_staging_sheet_read",\{p_character_id:characterId\}\)/);
assert.match(html,/els\.sheetReadTitle\.textContent=/);
assert.match(html,/els\.sheetReadSummary\.append\(wrap\)/);
assert.ok(!/\.innerHTML\s*=|console\.log\(\s*jwt|localStorage|sessionStorage/.test(html));
const source=html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
assert.ok(source,"Staging page script missing");
const checked=spawnSync(process.execPath,["--input-type=module","--check"],{input:source,encoding:"utf8"});
assert.equal(checked.status,0,"Staging read-only sheet page has syntax error: "+checked.stderr);
console.log("PASS: original character sheet reads require owner/DM, RLS invoker, no writes or token leaks.");
